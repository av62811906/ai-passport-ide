trans_id_t trans_pick(bool is_trainer, uint8_t wild_level,
                      uint8_t pet_level, bool open_biome, uint8_t *idx)
{
    uint8_t bits = is_trainer ? 1u : 0u;
    if ((int)wild_level >= (int)pet_level + 3) bits |= 2u;
    if (!open_biome) bits |= 4u;
    if (idx) *idx = bits;
    return (trans_id_t)bits;
}

trans_id_t trans_pick_encounter(uint16_t uid, uint8_t biome, bool stronger)
{
    static const trans_id_t variants[] = {TRANS_WAVE, TRANS_SPIRAL_IN,
        TRANS_SPECKLE, TRANS_H_STRIPES, TRANS_SHRINK, TRANS_SPIRAL_OUT,
        TRANS_V_STRIPES, TRANS_SPLIT};
    return variants[((uint32_t)uid + biome * 3u + (stronger ? 4u : 0u)) % 8u];
}

uint16_t trans_frames(trans_id_t id)
{
    return (id >= 0 && id < TRANS_COUNT) ? FRAMES[id] : 64;
}

bool trans_has_flash(trans_id_t id)
{
    return id == TRANS_DOUBLE_CIRCLE || id == TRANS_CIRCLE;
}

static bool circle_covered(bool double_circle, uint16_t q,
                           uint8_t gx, uint8_t gy)
{
    // 坐标乘 2，中心 (14.5,19.5) 变成整数 (29,39)。最远角 d²=2362。
    int32_t dx = (int32_t)gx * 2 - (TRANS_GRID_W - 1);
    int32_t dy = (int32_t)gy * 2 - (TRANS_GRID_H - 1);
    uint32_t d2 = (uint32_t)(dx * dx + dy * dy);
    uint32_t remain = 1000u - q;
    bool covered = (uint64_t)d2 * 1000000ULL >
                   (uint64_t)2362u * remain * remain;

    if (double_circle) {
        // d < r_max * p * 0.45；严格小于号与 Python 保持一致。
        if ((uint64_t)d2 * 10000000000ULL <
            (uint64_t)2362u * q * q * 2025u) {
            covered = true;
        }
    }
    return covered;
}

bool trans_tile_covered(trans_id_t id, uint16_t progress_q10,
                        uint8_t gx, uint8_t gy)
{
    if (gx >= TRANS_GRID_W || gy >= TRANS_GRID_H) return false;
    uint16_t q = progress_q10 > 1000 ? 1000 : progress_q10;

    switch (id) {
    case TRANS_DOUBLE_CIRCLE:
        return circle_covered(true, q, gx, gy);
    case TRANS_CIRCLE:
        return circle_covered(false, q, gx, gy);

    case TRANS_SPIRAL_OUT: {
        uint16_t done = (uint16_t)((uint32_t)TRANS_CELLS * q / 1000u);
        return SPIRAL_RANK[gy][gx] < done;
    }
    case TRANS_SPIRAL_IN: {
        uint16_t done = (uint16_t)((uint32_t)TRANS_CELLS * q / 1000u);
        return (TRANS_CELLS - 1u - SPIRAL_RANK[gy][gx]) < done;
    }

    case TRANS_H_STRIPES: {
        uint8_t even_done = (uint8_t)((uint32_t)TRANS_GRID_W * q / 1000u);
        if ((gy & 1u) == 0) return gx < even_done;
        if (q <= 500) return false;
        uint8_t odd_done = (uint8_t)((uint32_t)(TRANS_GRID_W * 2) *
                                     (q - 500u) / 1000u);
        return gx < odd_done;
    }

    case TRANS_V_STRIPES: {
        uint8_t even_done = (uint8_t)((uint32_t)TRANS_GRID_H * q / 1000u);
        if ((gx & 1u) == 0) return gy < even_done;
        if (q <= 500) return false;
        uint8_t odd_done = (uint8_t)((uint32_t)(TRANS_GRID_H * 2) *
                                     (q - 500u) / 1000u);
        return gy < odd_done;
    }

    case TRANS_SHRINK: {
        uint8_t band_y = (uint8_t)((195u * q) / 10000u + 1u);
        uint8_t band_x = (uint8_t)((145u * q) / 10000u + 1u);
        return gy < band_y || gy >= TRANS_GRID_H - band_y ||
               gx < band_x || gx >= TRANS_GRID_W - band_x;
    }

    case TRANS_SPLIT: {
        uint8_t half = (uint8_t)((195u * q) / 10000u + 1u);
        int16_t dy2 = (int16_t)gy * 2 - (TRANS_GRID_H - 1);
        if (dy2 < 0) dy2 = (int16_t)-dy2;
        return dy2 < (int16_t)half * 2;
    }

    case TRANS_WAVE: {
        // Fixed-point sine-shaped edge: no float/trig on ESP32-C3.
        static const int8_t wave[16] = {0,2,4,6,6,6,4,2,0,-2,-4,-6,-6,-6,-4,-2};
        int edge = (int)(q * (TRANS_GRID_W + 12u) / 1000u) - 6;
        return (int)gx < edge + wave[gy % 16];
    }
    case TRANS_SPECKLE: {
        // 37 is coprime to 1200: every cell has a unique reveal rank.
        uint32_t rank = ((uint32_t)gy * TRANS_GRID_W + gx) * 37u % TRANS_CELLS;
        return rank < (uint32_t)q * TRANS_CELLS / 1000u;
    }
    default:
        return false;
    }
}
